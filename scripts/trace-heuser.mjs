// Traces the Heuser College originals in public/brand/heuser/*.png into single-colour SVG paths (currentColor).
// Usage: node scripts/trace-heuser.mjs   (requires ImageMagick `magick` on PATH and the `potrace` dev dep)
// Writes: public/brand/heuser/heuser-mark.svg, heuser-college.svg, heuser.svg and src/components/brand/heuser-paths.ts
// The shapes are traced, never redrawn. "HEUSER" is cut from the traced wordmark by keeping the subpaths left of
// the gap between the R and the C, so it is the exact Heuser lettering.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import potrace from "potrace";

const dir = mkdtempSync(join(tmpdir(), "heuser-trace-"));
const trace = (file) => new Promise((res, rej) =>
  potrace.trace(readFileSync(file), { threshold: 128, turdSize: 8, optTolerance: 0.2 }, (err, svg) => (err ? rej(err) : res(svg))));
const pathOf = (svg) => svg.match(/ d="([^"]+)"/)[1];

/** Alpha channel → black shapes on white, cropped to the ink with a small margin. Returns [file, x, y, w, h]. */
function mask(src, name) {
  const out = join(dir, `${name}.png`);
  const box = execFileSync("magick", [src, "-alpha", "extract", "-threshold", "50%", "-format", "%@", "info:"]).toString(); // WxH+X+Y of the ink
  const [, w, h, x, y] = box.match(/(\d+)x(\d+)\+(\d+)\+(\d+)/).map(Number);
  execFileSync("magick", [src, "-alpha", "extract", "-negate", out]);
  return [out, x, y, w, h];
}

/** Splits a potrace path into subpaths (each starts with M) and returns them with their bounding boxes. */
function subpaths(d) {
  return d.trim().split(/(?=M)/).map((p) => {
    const nums = p.match(/-?\d+(\.\d+)?/g).map(Number);
    const xs = nums.filter((_, i) => i % 2 === 0), ys = nums.filter((_, i) => i % 2 === 1);
    return { d: p.trim(), minX: Math.min(...xs), maxX: Math.max(...xs), minY: Math.min(...ys), maxY: Math.max(...ys) };
  });
}
const round = (n) => Math.round(n * 10) / 10;
const vb = (x, y, w, h) => `${round(x)} ${round(y)} ${round(w)} ${round(h)}`;

const [markFile, mx, my, mw, mh] = mask("public/brand/heuser/heuser-mark-white.png", "mark");
const [wordFile, wx, wy, ww, wh] = mask("public/brand/heuser/heuser-college-black.png", "word");
const [markD, wordD] = await Promise.all([trace(markFile).then(pathOf), trace(wordFile).then(pathOf)]);

// Group subpaths into letters (a counter, like the hole in R, overlaps its letter), then keep H-E-U-S-E-R.
const parts = subpaths(wordD).sort((a, b) => a.minX - b.minX);
const letters = [];
for (const p of parts) {
  const last = letters.at(-1);
  if (last && p.minX < last.maxX) { last.items.push(p); last.maxX = Math.max(last.maxX, p.maxX); }
  else letters.push({ maxX: p.maxX, items: [p] });
}
if (letters.length !== 13) throw new Error(`expected 13 letters in HEUSERCOLLEGE, found ${letters.length}`);
const heuser = letters.slice(0, 6).flatMap((l) => l.items);
const gapAt = (letters[5].maxX + letters[6].items[0].minX) / 2;
const hMaxX = Math.max(...heuser.map((p) => p.maxX));
const heuserD = heuser.map((p) => p.d).join(" ");
// Per-letter paths + left edges, so the word can be letter-spaced (tracking) without touching any glyph.
const heuserLetters = letters.slice(0, 6).map((l) => ({ x: round(Math.min(...l.items.map((p) => p.minX))), w: round(l.maxX - Math.min(...l.items.map((p) => p.minX))), d: l.items.map((p) => p.d).join(" ") }));

const MARK_VIEWBOX = vb(mx, my, mw, mh);
const WORDMARK_VIEWBOX = vb(wx, wy, ww, wh);
const HEUSER_VIEWBOX = vb(wx, wy, hMaxX - wx, wh);

const svg = (viewBox, d, title) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-label="${title}"><path fill="currentColor" fill-rule="evenodd" d="${d}"/></svg>\n`;
writeFileSync("public/brand/heuser/heuser-mark.svg", svg(MARK_VIEWBOX, markD, "Heuser College"));
writeFileSync("public/brand/heuser/heuser-college.svg", svg(WORDMARK_VIEWBOX, wordD, "Heuser College"));
writeFileSync("public/brand/heuser/heuser.svg", svg(HEUSER_VIEWBOX, heuserD, "Heuser"));
writeFileSync(
  "src/components/brand/heuser-paths.ts",
  `// Generated by scripts/trace-heuser.mjs from public/brand/heuser/*.png. Do not edit by hand.
export const HEUSER_MARK_VIEWBOX = "${MARK_VIEWBOX}";
export const HEUSER_MARK = "${markD}";
export const HEUSER_WORDMARK_VIEWBOX = "${WORDMARK_VIEWBOX}";
export const HEUSER_WORDMARK = "${wordD}";
/** Just the bold "HEUSER", cut from the traced wordmark. */
export const HEUSER_WORD_VIEWBOX = "${HEUSER_VIEWBOX}";
export const HEUSER_WORD = "${heuserD}";
/** The same six letters one by one ({ x: left edge, w: width, d }), for letter-spaced lockups. */
export const HEUSER_LETTERS: { x: number; w: number; d: string }[] = ${JSON.stringify(heuserLetters)};
`,
);
console.log(`mark ${MARK_VIEWBOX} · wordmark ${WORDMARK_VIEWBOX} (${parts.length} subpaths) · HEUSER ${HEUSER_VIEWBOX} (${heuser.length} subpaths, cut at x=${round(gapAt)})`);

// Letter-spaced HEUSER as PNG (black for light surfaces, white for dark) for email clients, which drop inline SVG.
// Tracking 0.32 × cap height, matching <HeuserWord tracking={0.32}>. Rendered from the traced paths at 3× of 16px.
{
  const gap = 0.32 * wh, last = heuserLetters.at(-1);
  const w = last.x + last.w - heuserLetters[0].x + gap * (heuserLetters.length - 1);
  const tracked = (fill) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${heuserLetters[0].x} ${wy} ${round(w)} ${wh}">${heuserLetters
    .map((l, i) => `<path fill="${fill}" fill-rule="evenodd" transform="translate(${round(gap * i)} 0)" d="${l.d}"/>`).join("")}</svg>`;
  for (const [name, fill] of [["black", "#161616"], ["white", "#FFFFFF"]]) {
    const svgFile = join(dir, `heuser-word-${name}.svg`);
    writeFileSync(svgFile, tracked(fill));
    execFileSync("magick", ["-background", "none", "-density", "300", svgFile, "-resize", "x48", "-strip", `public/brand/heuser/heuser-word-${name}.png`]);
  }
  console.log(`email PNGs: heuser-word-{black,white}.png (aspect ${round(w / wh)}:1)`);
}
