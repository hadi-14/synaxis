// Regenerates src/components/brand/logo-paths.ts from public/logo/synaxis-logo.svg
import { readFileSync, writeFileSync } from "node:fs";
const svg = readFileSync("public/logo/synaxis-logo.svg", "utf8");
const [letters, x] = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
writeFileSync(
  "src/components/brand/logo-paths.ts",
  `// Generated by scripts/build-logo-component.mjs — do not edit.\nexport const LOGO_VIEWBOX = "0 0 890 126";\nexport const LOGO_LETTERS = ${JSON.stringify(letters)};\nexport const LOGO_X = ${JSON.stringify(x)};\n`,
);
console.log("ok");
